import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "ToolBox — Developer Utilities & Live Text Sync",
  description:
    "Fast, open developer utility workspace featuring real-time Live Text Share, QR Studio, and Link Fixer.",
};

const THEME_INIT_SCRIPT = `(function(){try{var t=localStorage.getItem("toolbox_theme");if(t==="light"){document.documentElement.classList.remove("dark");}else{document.documentElement.classList.add("dark");}}catch(e){document.documentElement.classList.add("dark");}})();`;

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased dark`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
      </head>
      <body className="min-h-full bg-[var(--bg-app)] text-[var(--text-main)] selection:bg-blue-500/30 selection:text-blue-900 dark:selection:text-blue-100 transition-colors">
        {children}
      </body>
    </html>
  );
}
